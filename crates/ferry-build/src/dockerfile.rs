/// Package to build: `.` when the root has Go files, else the single
/// directory under `cmd/`.
fn go_main_package(dir: &Path) -> String {
    let root_has_go = std::fs::read_dir(dir)
        .map(|rd| rd.flatten().any(|e| e.path().extension().is_some_and(|x| x == "go")))
        .unwrap_or(false);
    if root_has_go {
        return ".".to_string();
    }
    let cmds: Vec<String> = std::fs::read_dir(dir.join("cmd"))
        .map(|rd| {
            rd.flatten()
                .filter(|e| e.path().is_dir())
                .filter_map(|e| e.file_name().to_str().map(str::to_string))
                .filter(|n| n.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.')))
                .collect()
        })
        .unwrap_or_default();
    match cmds.as_slice() {
        [only] => format!("./cmd/{only}"),
        _ => ".".to_string(),
    }
}

fn go(dir: &Path, opts: &DockerfileOptions) -> Result<String> {
    let version = detect::go_version(dir).unwrap_or_else(|| DEFAULT_GO.to_string());
    let gomod = read_text(dir, "go.mod").unwrap_or_default();
    let local_replace = gomod.lines().any(|l| l.contains("=> ./") || l.contains("=> ../") || l.contains("=> /"));
    let vendored = dir.join("vendor").is_dir();
    let mod_cache = "--mount=type=cache,target=/go/pkg/mod".to_string();
    let build_cache = "--mount=type=cache,target=/root/.cache/go-build".to_string();

    let mut df = Df::new("Go app");
    df.line(format!("FROM golang:{version}-alpine AS build"));
    df.line("WORKDIR /src");
    df.args(&opts.build_arg_keys);
    df.blank();
    if exists(dir, "go.mod") && !local_replace && !vendored {
        df.line(if exists(dir, "go.sum") { "COPY go.mod go.sum ./" } else { "COPY go.mod ./" });
        df.run(std::slice::from_ref(&mod_cache), "go mod download");
        df.blank();
    }
    df.line("COPY . .");
    let steps: Vec<(bool, String)> = match nonempty(&opts.build_command) {
        Some(b) => vec![(false, "mkdir -p /out".into()), (true, b.to_string())],
        None => vec![
            (false, "mkdir -p /out".into()),
            (
                false,
                format!("CGO_ENABLED=0 go build -trimpath -ldflags=\"-s -w\" -o /out/app {}", go_main_package(dir)),
            ),
        ],
    };
    df.run_steps(&[mod_cache, build_cache], &steps);
    df.blank();
    df.line("FROM alpine:3.20");
    df.run(&[], "apk add --no-cache ca-certificates tzdata");
    df.line("WORKDIR /app");
    // The source tree stays available for runtime assets (templates, static
    // files) and Render-style start commands such as `./app`.
    df.line("COPY --from=build /src/ /app/");
    df.line("COPY --from=build /out/ /usr/local/bin/");
    df.blank();
    let start = if let Some(s) = nonempty(&opts.start_command) {
        Start::Shell(s.to_string())
    } else if let Some(p) = detect::procfile_command(dir, opts.service_type) {
        Start::Shell(p)
    } else {
        Start::Exec(vec!["/usr/local/bin/app".into()])
    };
    emit_start(&mut df, start);
    Ok(df.finish())
}

