fn ruby(dir: &Path, opts: &DockerfileOptions) -> Result<String> {
    let version = detect::ruby_version(dir).unwrap_or_else(|| DEFAULT_RUBY.to_string());
    let gemfile = read_text(dir, "Gemfile").unwrap_or_default();
    let needs_tree = gemfile
        .lines()
        .map(str::trim)
        .any(|l| !l.starts_with('#') && (l.starts_with("gemspec") || l.contains("path:") || l.contains(":path")));
    let mut df = Df::new("Ruby app");
    df.line(format!("FROM ruby:{version}-slim"));
    df.run(
        &[],
        "apt-get update && apt-get install -y --no-install-recommends build-essential git libyaml-dev pkg-config \
         && rm -rf /var/lib/apt/lists/*",
    );
    df.line("WORKDIR /app");
    df.args(&opts.build_arg_keys);
    df.blank();
    if needs_tree || !exists(dir, "Gemfile") {
        df.line("COPY . .");
        df.run(&[], "bundle install");
    } else {
        df.line(if exists(dir, "Gemfile.lock") { "COPY Gemfile Gemfile.lock ./" } else { "COPY Gemfile ./" });
        df.run(&[], "bundle install");
        df.blank();
        df.line("COPY . .");
    }
    if let Some(b) = nonempty(&opts.build_command) {
        df.run(&[], b);
    }
    df.blank();
    let start = if let Some(s) = nonempty(&opts.start_command) {
        Start::Shell(s.to_string())
    } else if let Some(p) = detect::procfile_command(dir, opts.service_type) {
        Start::Shell(p)
    } else if exists(dir, "config.ru") {
        Start::Shell("bundle exec rackup -o 0.0.0.0 -p ${PORT:-10000}".to_string())
    } else {
        missing_start("Ruby", ", or a config.ru for Rack apps", opts)?
    };
    emit_start(&mut df, start);
    Ok(df.finish())
}

