fn python(dir: &Path, opts: &DockerfileOptions) -> Result<String> {
    let version = detect::python_version(dir).unwrap_or_else(|| DEFAULT_PYTHON.to_string());
    let mut df = Df::new("Python app");
    df.line(format!("FROM python:{version}-slim"));
    df.line("ENV PYTHONUNBUFFERED=1 \\");
    df.line("    PYTHONDONTWRITEBYTECODE=1 \\");
    df.line("    PIP_DISABLE_PIP_VERSION_CHECK=1 \\");
    df.line("    PIP_ROOT_USER_ACTION=ignore");
    df.line("WORKDIR /app");
    df.args(&opts.build_arg_keys);
    df.blank();

    if dir.join("requirements.txt").is_file() {
        let reqs = read_text(dir, "requirements.txt").unwrap_or_default();
        // References to other files (-r, -c, -e ., local paths) need the full tree.
        let needs_tree = reqs.lines().map(str::trim).any(|l| {
            l.starts_with("-r")
                || l.starts_with("-c")
                || l.starts_with("-e")
                || l.starts_with("--requirement")
                || l.starts_with("--constraint")
                || l.starts_with("--editable")
                || l.starts_with('.')
                || l.starts_with("file:")
        });
        if needs_tree {
            df.line("COPY . .");
            df.run(&[], "pip install --no-cache-dir -r requirements.txt");
        } else {
            df.line("COPY requirements.txt ./");
            df.run(&[], "pip install --no-cache-dir -r requirements.txt");
            df.blank();
            df.line("COPY . .");
        }
    } else if dir.join("pyproject.toml").is_file() {
        df.line("COPY . .");
        df.run(&[], "pip install --no-cache-dir .");
    } else if dir.join("Pipfile").is_file() {
        let has_lock = dir.join("Pipfile.lock").is_file();
        df.line(if has_lock { "COPY Pipfile Pipfile.lock ./" } else { "COPY Pipfile ./" });
        df.run(
            &[],
            if has_lock {
                "pip install --no-cache-dir pipenv && pipenv install --system --deploy"
            } else {
                "pip install --no-cache-dir pipenv && pipenv install --system --skip-lock"
            },
        );
        df.blank();
        df.line("COPY . .");
    } else {
        df.line("COPY . .");
    }
    if let Some(b) = nonempty(&opts.build_command) {
        df.run(&[], b);
    }
    df.blank();

    let start = if let Some(s) = nonempty(&opts.start_command) {
        Start::Shell(s.to_string())
    } else if let Some(p) = detect::procfile_command(dir, opts.service_type) {
        Start::Shell(p)
    } else if let Some(f) = ["main.py", "app.py"].iter().find(|f| dir.join(f).is_file()) {
        Start::Exec(vec!["python".into(), f.to_string()])
    } else {
        missing_start("Python", ", or a main.py / app.py file", opts)?
    };
    emit_start(&mut df, start);
    Ok(df.finish())
}

