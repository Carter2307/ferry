/** The document with its paths in PATH_ORDER (only used to lay out the pages). */
function withTaskOrder(document) {
  const paths = Object.entries(document.paths ?? {});
  const rank = (p) => {
    const i = PATH_ORDER.indexOf(p);
    return i === -1 ? PATH_ORDER.length : i;
  };
  const sorted = paths
    .map((entry, index) => ({ entry, index }))
    .sort((a, b) => rank(a.entry[0]) - rank(b.entry[0]) || a.index - b.index)
    .map(({ entry }) => entry);
  return { ...document, paths: Object.fromEntries(sorted) };
}

