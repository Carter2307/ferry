async function main() {
  console.log('• dumping the OpenAPI document and the CLI/server help (cargo run)…');
  const openapiJson = cargoRun('ferryd', ['--dump-openapi']);
  const cliMarkdown = cargoRun('ferry-cli', ['markdown-help']);
  const ferrydMarkdown = cargoRun('ferryd', ['--dump-markdown-help']);
  const ferrydHelp = cargoRun('ferryd', ['--help']);

  const document = JSON.parse(openapiJson);
  if (!String(document.openapi ?? '').startsWith('3.')) throw new Error('ferryd --dump-openapi did not print an OpenAPI 3 document');

  /** @type {Record<string, string>} path (relative to docs/) → content */
  const files = {
    'openapi/ferry.json': openapiJson.endsWith('\n') ? openapiJson : `${openapiJson}\n`,
    'content/docs/reference/cli.mdx': cliPage(cliMarkdown),
    'content/docs/reference/server-options.mdx': serverOptionsPage(ferrydMarkdown, ferrydHelp),
    ...(await apiPages(document)),
  };

  // Files under the API directory that the generator no longer produces.
  const apiAbs = path.join(DOCS_DIR, API_DIR);
  const existing = existsSync(apiAbs) ? (await readdir(apiAbs)).map((f) => `${API_DIR}/${f}`) : [];
  const stale = existing.filter((f) => !(f in files));

  const changed = [];
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(DOCS_DIR, rel);
    const current = existsSync(abs) ? await readFile(abs, 'utf8') : null;
    if (current !== content) changed.push(rel);
  }

  if (check) {
    if (changed.length === 0 && stale.length === 0) {
      console.log(`✓ ${Object.keys(files).length} generated files are up to date.`);
      return;
    }
    for (const f of changed) console.error(`✖ stale: ${f}`);
    for (const f of stale) console.error(`✖ no longer generated: ${f}`);
    console.error('\nRun `npm run generate` in docs/ and commit the result.');
    process.exitCode = 1;
    return;
  }

  for (const rel of changed) {
    const abs = path.join(DOCS_DIR, rel);
    await mkdir(path.dirname(abs), { recursive: true });
    await writeFile(abs, files[rel]);
    console.log(`  wrote ${rel}`);
  }
  for (const rel of stale) {
    await rm(path.join(DOCS_DIR, rel));
    console.log(`  removed ${rel}`);
  }
  console.log(`✓ ${Object.keys(files).length} generated files (${changed.length} updated, ${stale.length} removed).`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
