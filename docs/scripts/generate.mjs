function cargoRun(pkg, args) {
  try {
    return execFileSync('cargo', ['run', '-q', '-p', pkg, '--', ...args], {
      cwd: REPO_DIR,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
      stdio: ['ignore', 'pipe', 'inherit'],
    });
  } catch (err) {
    console.error(`\n✖ \`cargo run -q -p ${pkg} -- ${args.join(' ')}\` failed (run from ${REPO_DIR}).`);
    console.error('  The generator needs the Rust toolchain; the committed files keep `npm run build` working without it.');
    throw err;
  }
}

