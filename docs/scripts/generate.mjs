/**
 * Escapes the characters MDX would read as JSX or expressions (`<`, `{`, `}`)
 * outside code spans. Fenced code blocks are left untouched; a code span may
 * cross line breaks inside a paragraph, like in CommonMark.
 */
function escapeMdx(markdown) {
  const escapeParagraph = (text) => {
    let out = '';
    let i = 0;
    while (i < text.length) {
      if (text[i] === '`') {
        let n = 0;
        while (text[i + n] === '`') n++;
        const fence = '`'.repeat(n);
        const close = text.indexOf(fence, i + n);
        if (close !== -1) {
          out += text.slice(i, close + n);
          i = close + n;
          continue;
        }
        out += fence;
        i += n;
        continue;
      }
      const c = text[i];
      out += c === '<' || c === '{' || c === '}' ? `\\${c}` : c;
      i++;
    }
    return out;
  };

  const out = [];
  let paragraph = [];
  let inFence = false;
  const flush = () => {
    if (paragraph.length > 0) out.push(escapeParagraph(paragraph.join('\n')));
    paragraph = [];
  };
  for (const line of markdown.split('\n')) {
    if (/^\s*(```|~~~)/.test(line)) {
      flush();
      inFence = !inFence;
      out.push(line);
    } else if (inFence) {
      out.push(line);
    } else if (line.trim() === '') {
      flush();
      out.push(line);
    } else {
      paragraph.push(line);
    }
  }
  flush();
  return out.join('\n');
}

/** Plain text for frontmatter: no Markdown code spans, single line. */
function plain(text) {
  return text.replace(/`/g, '').replace(/\s+/g, ' ').trim();
}

function yamlString(text) {
  return JSON.stringify(text); // a JSON string is a valid YAML double-quoted scalar
}

function frontmatter(fields) {
  const lines = Object.entries(fields)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => `${k}: ${typeof v === 'string' ? yamlString(v) : JSON.stringify(v)}`);
  return `---\n${lines.join('\n')}\n---\n`;
}

/**
 * clap-markdown output → MDX body: drops its title, preamble and HTML footer,
 * turns `###### **Options:**` into bold labels (so the TOC only lists commands),
 * removes the `↴` markers and escapes MDX-sensitive characters.
 */
function clapMarkdownToMdx(md, { keepOverview }) {
  let text = md.replace(/\r\n/g, '\n');
  const footer = text.indexOf('<hr/>');
  if (footer !== -1) text = text.slice(0, footer);
  // `**Usage:** \`ferry env [OPTIONS] <NAME>\n       env <COMMAND>\`` → a code block
  // with one full command per line (clap-markdown drops the binary name on
  // continuation lines; the terminal help prints it).
  text = text.replace(/^\*\*Usage:\*\* `([^`]+)`$/gm, (_, usage) => {
    const [first, ...rest] = usage.split('\n').map((l) => l.trim());
    const bin = first.split(' ')[0];
    const forms = [first, ...rest.map((l) => (l.startsWith(`${bin} `) ? l : `${bin} ${l}`))];
    return `**Usage**\n\n\`\`\`text\n${forms.join('\n')}\n\`\`\``;
  });
  const lines = text.split('\n');
  const out = [];
  let skippingOverview = false;
  for (const line of lines) {
    if (/^# Command-Line Help for /.test(line)) continue;
    if (/^This document contains the help content for /.test(line)) continue;
    if (line.trim() === '**Command Overview:**') {
      if (keepOverview) {
        out.push('## Command overview');
      } else {
        skippingOverview = true;
      }
      continue;
    }
    if (skippingOverview) {
      if (line.startsWith('* [') || line.trim() === '') continue;
      skippingOverview = false;
    }
    const label = /^#{3,6} \*\*(.+?):?\*\*\s*$/.exec(line);
    if (label) {
      out.push(`**${label[1].replace(/:$/, '')}**`);
      continue;
    }
    out.push(line.replace(/↴/g, ''));
  }
  return escapeMdx(out.join('\n'))
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/**
 * `ferryd --help` → { '--data-dir': 'FERRY_DATA_DIR', … }: the options of the
 * server (the ones listed without a command) and their environment variables.
 * An option without a variable maps to `undefined`.
 */
function ferrydEnvVars(help) {
  const env = {};
  const isFlag = (line) => /^\s+(?:-\w, )?(--[a-z0-9-]+)(?: <[A-Z_]+>)?\s*$/.exec(line);
  const lines = help.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const flag = isFlag(lines[i]);
    if (!flag) continue;
    env[flag[1]] = undefined;
    // The description follows, then (after a blank line in the long help) `[env: …]`.
    for (let j = i + 1; j < lines.length && !isFlag(lines[j]); j++) {
      const m = /\[env: ([A-Z0-9_]+)=?[^\]]*\]/.exec(lines[j]);
      if (m) {
        env[flag[1]] = m[1];
        break;
      }
    }
  }
  return env;
}

/** A Markdown table cell: one line, `|` escaped. */
function cell(text) {
  return text.replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|').trim();
}

/**
 * clap-markdown lists arguments and options as bullets, with the default value
 * (and, for ferryd, the environment variable) on indented lines:
 *
 *   * `-t`, `--type <TYPE>` — Service type: web, pserv, worker, cron, static
 *
 *     Default value: `web`
 *
 * This turns every **Arguments** and **Options** list into a table, which is easier
 * to scan on long commands. With `env` (ferryd), each option also shows its
 * environment variable. Returns the MDX and the options that have no variable.
 */
function optionListsToTables(mdx, env) {
  const lines = mdx.split('\n');
  const out = [];
  const seenEnv = new Set();
  const withoutEnv = [];
  let i = 0;
  while (i < lines.length) {
    const heading = lines[i];
    const kind = heading === '**Options**' ? 'Option' : heading === '**Arguments**' ? 'Argument' : null;
    out.push(heading);
    i++;
    if (!kind) continue;

    /** @type {{ term: string, flag?: string, description: string, notes: Record<string, string> }[]} */
    const items = [];
    while (i < lines.length) {
      const line = lines[i];
      const next = lines[i + 1] ?? '';
      if (line.startsWith('* ')) {
        const m = /^\* (.+?) — (.*)$/.exec(line) ?? /^\* (.+)$/.exec(line);
        const flag = /`(--[a-z0-9-]+)(?: [^`]*)?`/.exec(m[1]);
        items.push({ term: m[1], flag: flag?.[1], description: m[2] ?? '', notes: {} });
      } else if (line.startsWith('  ') && items.length > 0) {
        const m = /^\s+([A-Z][A-Za-z ]*): (.*)$/.exec(line);
        const item = items[items.length - 1];
        if (m) item.notes[m[1]] = m[2];
        else item.description += ` ${line.trim()}`;
      } else if (line.trim() === '' && items.length > 0 && (next.startsWith('  ') || next.startsWith('* '))) {
        // blank line between a bullet and its indented notes
      } else if (line.trim() === '' && items.length === 0) {
        // blank line after the label
      } else {
        break;
      }
      i++;
    }
    if (items.length === 0) throw new Error(`empty **${kind}s** list in the clap-markdown output`);

    for (const item of items) {
      if (!env) continue;
      const variable = item.flag ? env[item.flag] : undefined;
      if (variable) {
        seenEnv.add(item.flag);
        item.term += `<br />\`${variable}\``;
      } else if (item.flag) {
        withoutEnv.push(item.flag);
      }
    }
    const hasDefault = items.some((item) => item.notes['Default value']);
    const first = kind === 'Argument' ? 'Argument' : env ? 'Option and environment variable' : 'Option';
    const header = [first, 'Description', ...(hasDefault ? ['Default'] : [])];
    const rows = items.map((item) => {
      const extra = Object.entries(item.notes)
        .filter(([key]) => key !== 'Default value')
        .map(([key, value]) => ` ${key}: ${value}.`)
        .join('');
      const row = [item.term, `${item.description}${extra}`];
      if (hasDefault) row.push(item.notes['Default value'] ?? '');
      return `| ${row.map(cell).join(' | ')} |`;
    });
    out.push('', `| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`, ...rows, '');
  }
  if (env) {
    const missing = Object.keys(env).filter((f) => env[f] && !seenEnv.has(f));
    if (missing.length > 0) {
      throw new Error(`ferryd options with an env var but no entry in --dump-markdown-help: ${missing.join(', ')}`);
    }
  }
  return { mdx: out.join('\n').replace(/\n{3,}/g, '\n\n'), withoutEnv };
}

